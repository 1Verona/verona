(() => {
  const bindings = [];
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement.closest('svg,script,style,.language-toggle')) continue;
    const key = node.textContent.trim();
    if (!Object.hasOwn(portugueseCopy, key)) continue;
    const prefix = node.textContent.slice(0, node.textContent.indexOf(key));
    const suffix = node.textContent.slice(prefix.length + key.length);
    bindings.push({node, key, prefix, suffix});
  }
  const attributes = [];
  document.querySelectorAll('[aria-label],[alt],[data-title],meta[name="description"]').forEach(element => {
    ['aria-label','alt','data-title','content'].forEach(attribute => {
      const key = element.getAttribute(attribute);
      if (key && Object.hasOwn(portugueseCopy, key)) attributes.push({element,attribute,key});
    });
  });
  const englishTitle = document.title;
  function setLanguage(language, persist = false) {
    const pt = language === 'pt';
    document.documentElement.lang = pt ? 'pt-BR' : 'en';
    bindings.forEach(({node,key,prefix,suffix}) => {node.textContent = prefix + (pt ? portugueseCopy[key] : key) + suffix;});
    attributes.forEach(({element,attribute,key}) => {element.setAttribute(attribute,pt ? portugueseCopy[key] : key);});
    document.title = pt ? portugueseCopy[englishTitle] : englishTitle;
    document.querySelector('.language-toggle').setAttribute('aria-label',pt ? 'Idioma' : 'Language');
    document.querySelectorAll('[data-language]').forEach(button => {button.setAttribute('aria-pressed',String(button.dataset.language === language));});
    if (persist) {try {localStorage.setItem('verona-language',language);} catch {}}
    window.dispatchEvent(new CustomEvent('languagechange', {detail: {language}}));
  }
  document.querySelectorAll('[data-language]').forEach(button => {button.addEventListener('click',() => setLanguage(button.dataset.language,true));});
  let language = 'en';
  try {if (localStorage.getItem('verona-language') === 'pt') language = 'pt';} catch {}
  setLanguage(language);
})();
